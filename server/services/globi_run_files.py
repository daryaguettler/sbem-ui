"""Write globi's run files from a project's saved artifacts.

The project already holds the inputs globi reads (semantic-fields.yaml, component-map.yaml,
components-lib.db, gis/buildings-sampled.geojson or gis/buildings.geojson, schedule-variability.yaml). This adds the files that
point at them, each validated with globi's own model before it is written:

- building.yml: one building for `globi simulate` (MinimalBuildingSpec)
- artifacts.yml, gis-preprocessor.yml, manifest.yml: a batch run over the saved GIS for
  `globi submit manifest` (FileConfig, DeterministicGISPreprocessorConfig, GloBIExperimentSpec)

globi resolves paths against the directory it runs in (its repo root, via make). So paths are
written relative to the globi checkout when the project sits inside it -- which is also what
`make cli` (Docker) needs -- and absolute otherwise.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import yaml
from pydantic import ValidationError

from services.globi_component_map import SCENARIO, building_contexts, check_against_library
from services.workspace import ProjectWorkspace

HEADER = "# Generated by SBEM UI (Model Execution) from this project's saved files.\n"


class GlobiFilesError(Exception):
    """Raised when the project can't produce valid run files yet."""


def globi_root() -> Path:
    """The globi checkout sbem-ui is installed from (editable path dependency on ../globi)."""
    import globi

    return Path(globi.__file__).resolve().parents[2]


def _ref(path: Path) -> str:
    path = path.resolve()
    try:
        return str(path.relative_to(globi_root()))
    except ValueError:
        return str(path)


def saved_gis(workspace: ProjectWorkspace) -> Path | None:
    """The stock a batch run covers: Sampling's buildings × draws, else the saved enriched GIS."""
    for name in ("buildings-sampled.geojson", "buildings.geojson"):
        path = workspace.path("gis_dir") / name
        if path.exists():
            return path
    return None


def _is_remote(value: str) -> bool:
    return value.startswith(("http://", "https://", "s3://"))


def run_file_status(workspace: ProjectWorkspace) -> dict[str, Any]:
    """What the Model Execution form needs: saved fields and options, weather files, the GIS."""
    path = workspace.path("semantic_fields")
    doc = yaml.safe_load(path.read_text()) if path.exists() else {}
    fields = [
        {"name": field["Name"], "options": field.get("Options") or []}
        for field in (doc or {}).get("Fields") or []
    ]
    weather_dir = workspace.path("weather_dir")
    weather = sorted(str(p.relative_to(workspace.root)) for p in weather_dir.glob("*.zip")) if weather_dir.exists() else []
    gis = saved_gis(workspace)
    return {
        "fields": fields,
        "weather": weather,
        "gisFile": str(gis.relative_to(workspace.root)) if gis else None,
        "componentMapSaved": workspace.path("component_map").exists(),
    }


def generate_run_files(
    workspace: ProjectWorkspace,
    name: str,
    epwzip_file: str,
    context: dict[str, str],
    building: dict[str, Any],
    scenario: str = "Baseline",
) -> dict[str, Any]:
    """Write building.yml, and the batch files when a GIS has been saved. Returns what was written."""
    from globi.models.configs import (
        DeterministicGISPreprocessorConfig,
        FileConfig,
        GloBIExperimentSpec,
    )
    from globi.models.tasks import MinimalBuildingSpec

    status = run_file_status(workspace)
    if not status["fields"]:
        raise GlobiFilesError("Save your building characteristics first (Building Characteristics → Save).")
    if not status["componentMapSaved"]:
        raise GlobiFilesError("Save the model parts first (Building Characteristics → Save).")
    if not workspace.path("components_db").exists():
        raise GlobiFilesError("The project has no components-lib.db.")

    problems = [
        f"{field['name']}: choose one of {', '.join(map(str, field['options']))}."
        for field in status["fields"]
        if str(context.get(field["name"], "")) not in map(str, field["options"])
    ]
    if problems:
        raise GlobiFilesError("Building values: " + " ".join(problems))
    _require_library(workspace, {"contexts": [context], "buildings": [1], "unmapped": [], "total": 1, "source": "this building"})

    if not epwzip_file:
        raise GlobiFilesError("Choose a weather file (.zip with .epw and .ddy, local path or URL).")
    if _is_remote(epwzip_file):
        weather = epwzip_file
    else:
        local = workspace.root / epwzip_file
        if not local.exists():
            raise GlobiFilesError(f"Weather file {epwzip_file} does not exist.")
        weather = _ref(local)

    inputs = {
        "db_file": _ref(workspace.path("components_db")),
        "semantic_fields_file": _ref(workspace.path("semantic_fields")),
        "component_map_file": _ref(workspace.path("component_map")),
        "epwzip_file": weather,
    }
    documents: dict[str, dict[str, Any]] = {
        "building": {**inputs, "semantic_field_context": context, **building},
    }
    warnings: list[str] = []
    gis = saved_gis(workspace)
    if gis:
        _require_library(workspace, building_contexts(workspace))
        documents["artifacts"] = {"gis_file": _ref(gis), **inputs}
        documents["gis_preprocessor"] = DeterministicGISPreprocessorConfig().model_dump(mode="json")
        manifest = {
            "name": name,
            "scenario": scenario,
            "hourly_data_config": None,
            "file_config": _ref(workspace.path("artifacts")),
            "gis_preprocessor_config": _ref(workspace.path("gis_preprocessor")),
        }
        variability = workspace.path("schedule_variability")
        variability_doc = yaml.safe_load(variability.read_text()) if variability.exists() else None
        if variability_doc is not None:
            manifest["schedule_variability_config"] = _ref(variability)
        # globi sets the Scenario column from the manifest, so each Scenario value is its own run
        scenarios = next((f["options"] for f in status["fields"] if f["name"] == SCENARIO), None) or [scenario]
        documents["manifest"] = {**manifest, "scenario": str(scenarios[0])}
        for other in scenarios[1:]:
            documents[f"manifest:{other}"] = {**manifest, "scenario": str(other)}

        columns = _geojson_columns(gis)
        missing = [field["name"] for field in status["fields"] if field["name"] not in columns]
        if missing:
            warnings.append(
                f"The saved GIS has no column for {', '.join(missing)}. A batch run needs a value per "
                "building for every field, and globi doesn't sample priors: make them From my data, or write sampled buildings (Sampling)."
            )
    else:
        warnings.append(
            "No buildings saved to the project (Sampling → Write sampled buildings, or Building "
            "Characteristics → GloBI files → Save to project, from a GeoJSON), so only building.yml was written."
        )

    try:
        MinimalBuildingSpec.model_validate(documents["building"])
        if "manifest" in documents:
            # validate with the referenced files inlined; globi loads them from disk at run time
            FileConfig.model_validate(documents["artifacts"])
            inlined = {
                **documents["manifest"],
                "file_config": documents["artifacts"],
                "gis_preprocessor_config": documents["gis_preprocessor"],
            }
            if "schedule_variability_config" in inlined:
                inlined["schedule_variability_config"] = variability_doc
            GloBIExperimentSpec.model_validate(inlined)
    except ValidationError as exc:
        raise GlobiFilesError(str(exc)) from exc

    paths = {key: _document_path(workspace, key) for key in documents}
    for key, document in documents.items():
        paths[key].write_text(HEADER + yaml.safe_dump(document, sort_keys=False))

    slug = "".join(c if c.isalnum() else "-" for c in name).strip("-").lower() or "sbem"
    commands = {"simulate": f"make cli-native simulate -- --config {_ref(workspace.path('building'))} --output-dir outputs/{slug}"}
    if "manifest" in documents:
        commands["batch"] = "\n".join(
            f"make cli submit manifest -- --path {_ref(paths[key])} --max-sims 5" for key in documents if key.startswith("manifest")
        )
    return {
        "written": [paths[key].relative_to(workspace.root).as_posix() for key in documents],
        "warnings": warnings,
        "commands": commands,
        "cwd": str(globi_root()),
    }


def _document_path(workspace: ProjectWorkspace, key: str) -> Path:
    """Run files live at their file keys; extra scenarios' manifests sit next to manifest.yml."""
    if not key.startswith("manifest:"):
        return workspace.path(key)
    slug = "".join(c if c.isalnum() else "-" for c in key.split(":", 1)[1]).strip("-").lower()
    return workspace.path("manifest").with_name(f"manifest-{slug}.yml")


def _require_library(workspace: ProjectWorkspace, found: dict[str, Any]) -> None:
    """Refuse to write run files globi would fail on: every building has to resolve."""
    result = check_against_library(
        workspace.read_generated_component_map() or {}, workspace.components_db_path, found
    )
    if not result["ok"]:
        raise GlobiFilesError(
            f"The component library doesn't cover {found['source']}: " + " ".join(result["errors"][:3])
        )


def _geojson_columns(path: Path) -> set[str]:
    features = json.loads(path.read_text()).get("features") or []
    return set((features[0].get("properties") or {}) if features else {})
